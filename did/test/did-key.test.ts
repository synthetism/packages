import { describe, expect, it } from "vitest";
import {
  DidKeyError,
  base58btcEncode,
  didKeyFromPublicKey,
  isDidKey,
  publicKeyFromDidKey,
} from "../src/index.js";

/**
 * A real identity minted by the previous stack — so this is a byte-for-byte
 * compatibility check against data that already exists in the wild, not a
 * self-consistent round-trip.
 */
const REAL_PUBLIC_KEY_HEX =
  "b078fed776413d8be5918ef229480acb51586fed28b8eeec4066077f84547784";
const REAL_DID = "did:key:z6MkrL8otjELxqEcmQZHM11UE1n9czAYSWNLQKRfXQH1ypnw";

describe("didKeyFromPublicKey", () => {
  it("reproduces a DID from the live stack, byte for byte", () => {
    expect(didKeyFromPublicKey(REAL_PUBLIC_KEY_HEX)).toBe(REAL_DID);
  });

  it("uses the standard z6Mk Ed25519 prefix", () => {
    expect(didKeyFromPublicKey(REAL_PUBLIC_KEY_HEX).startsWith("did:key:z6Mk")).toBe(
      true,
    );
  });

  it("rejects a key that is not 32 bytes", () => {
    expect(() => didKeyFromPublicKey("deadbeef")).toThrow(DidKeyError);
  });

  it("rejects non-hex input", () => {
    expect(() => didKeyFromPublicKey("zz".repeat(32))).toThrow(/hex/);
  });
});

describe("publicKeyFromDidKey", () => {
  it("recovers the public key", () => {
    expect(publicKeyFromDidKey(REAL_DID)).toBe(REAL_PUBLIC_KEY_HEX);
  });

  it("round-trips", () => {
    expect(didKeyFromPublicKey(publicKeyFromDidKey(REAL_DID))).toBe(REAL_DID);
  });

  it("throws on a non-did:key", () => {
    expect(() => publicKeyFromDidKey("did:web:example.com")).toThrow(DidKeyError);
  });

  it("throws when the multibase prefix is missing", () => {
    expect(() => publicKeyFromDidKey("did:key:6MkrL8otjELxqEcmQZHM11UE1n9")).toThrow(
      DidKeyError,
    );
  });

  it("rejects a non-Ed25519 multicodec instead of misreading it", () => {
    // secp256k1-pub is 0xe701; a valid base58 string with the wrong codec.
    const secp256k1 = `did:key:z${base58btcEncode(
      Uint8Array.from([0xe7, 0x01, ...new Uint8Array(33)]),
    )}`;
    expect(() => publicKeyFromDidKey(secp256k1)).toThrow(/multicodec/);
  });

  it("rejects a payload of the wrong length", () => {
    const short = `did:key:z${base58btcEncode(Uint8Array.from([0xed, 0x01, 1, 2, 3]))}`;
    expect(() => publicKeyFromDidKey(short)).toThrow(DidKeyError);
  });
});

describe("isDidKey", () => {
  it("accepts a well-formed did:key", () => {
    expect(isDidKey(REAL_DID)).toBe(true);
  });

  it("rejects everything else without throwing", () => {
    expect(isDidKey("did:web:example.com")).toBe(false);
    expect(isDidKey("did:key:z6Mk")).toBe(false);
    expect(isDidKey("")).toBe(false);
    expect(isDidKey(undefined)).toBe(false);
    expect(isDidKey(42)).toBe(false);
    expect(isDidKey(null)).toBe(false);
  });
});

// ---------------------------------------------------------------------------
// External reference vectors.
//
// Every DID below was produced *outside* this codebase — by the W3C spec, by an
// RFC 8032 test vector, or by the previous stack. None of them were generated by
// the implementation under test, which is the point: a self-consistent round-trip
// proves nothing about whether we agree with the rest of the world.
// ---------------------------------------------------------------------------

describe("external reference vectors", () => {
  const RFC_8032_PUBLIC_KEY = "d75a980182b10ab7d54bfed3c964073a0ee172f3daa62325af021a68f707511a";
  const W3C_SPEC_DID = "did:key:z6MktwupdmLXVVqTzCw4i46r4uGyosGXRnR3XjN4Zq7oMMsw";
  const W3C_EXAMPLE_DID = "did:key:z6MkhaXgBZDvotDkL5257faiztiGiC2QtKLGpbnnEGta2doK";

  it("maps the RFC 8032 test-vector key to the W3C spec DID", () => {
    expect(didKeyFromPublicKey(RFC_8032_PUBLIC_KEY)).toBe(W3C_SPEC_DID);
  });

  it("round-trips every externally-produced did:key, byte for byte", () => {
    for (const did of [W3C_SPEC_DID, W3C_EXAMPLE_DID, REAL_DID]) {
      const publicKeyHex = publicKeyFromDidKey(did);
      expect(publicKeyHex).toMatch(/^[0-9a-f]{64}$/);
      expect(didKeyFromPublicKey(publicKeyHex)).toBe(did);
    }
  });

  it("resolves a DID URL to the same key as its base DID", () => {
    const base = publicKeyFromDidKey(W3C_EXAMPLE_DID);
    expect(publicKeyFromDidKey(`${W3C_EXAMPLE_DID}#keys-1`)).toBe(base);
    expect(publicKeyFromDidKey(`${W3C_EXAMPLE_DID}#key-2`)).toBe(base);
    expect(isDidKey(`${W3C_EXAMPLE_DID}#keys-1`)).toBe(true);
  });

  it("rejects did:key values for other curves rather than misreading them", () => {
    // secp256k1 (0xe701) and x25519 (0xec01) — valid base58, wrong multicodec.
    const secp256k1 = "did:key:zQ3shZtr1sUnrETvXQSyvnEnpFDBXGKmdk7NxELbWHgxKrNbF";
    const x25519 = "did:key:z6LSkdrX4EvewpktHBjvNxRDogPdC5iVF8LT3LPKefGAgi89";

    expect(isDidKey(secp256k1)).toBe(false);
    expect(isDidKey(x25519)).toBe(false);
    expect(() => publicKeyFromDidKey(secp256k1)).toThrow(DidKeyError);
    expect(() => publicKeyFromDidKey(x25519)).toThrow(DidKeyError);
  });

  it("rejects the malformed DIDs the old suite collected", () => {
    for (const bad of [
      "did:key",
      "did:key:",
      "did:key:invalid-encoding",
      "did:key:spaces are bad",
      "did:key:special@chars#",
      "did:key:z6Mk#fragment-without-valid-did",
      "did:web:example.com",
      "did:invalid:test",
      "did:method:",
    ]) {
      expect(isDidKey(bad)).toBe(false);
    }
  });
});
